#!/usr/bin/env python3
"""Add (or update) one person's isolated backend instance.  Usage:  python deploy/new_user.py <name> [--domain example.com]

Keeps one small JSON per person in deploy/users/ (port + token) and regenerates ../docker-compose.yml from all of them,
so re-running is safe: an existing person keeps their port and token (use --rotate-token to change the token).
Also writes deploy/users/<name>.txt (URL + token to paste into the app). Standard library only; both are git-ignored."""
from __future__ import annotations

import argparse
import json
import re
import secrets
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
USERS = HERE / "users"
COMPOSE = ROOT / "docker-compose.yml"
FIRST_PORT = 8001
NAME_RE = re.compile(r"^[a-z0-9](?:[a-z0-9-]{0,28}[a-z0-9])?$")


def load_users() -> dict[str, dict]:
    out = {}
    for p in sorted(USERS.glob("*.json")):
        out[p.stem] = json.loads(p.read_text(encoding="utf-8"))
    return out


def render_compose(users: dict[str, dict], eleven_total: int) -> str:
    share = eleven_total // max(1, len(users))
    lines = [
        "# GENERATED by deploy/new_user.py -- do not edit by hand (re-run the script). Contains tokens: git-ignored.",
        "services:",
    ]
    for name, u in users.items():
        lines += [
            f"  fitness-{name}:",
            "    build: .",
            "    image: fitness-backend:local",
            "    restart: unless-stopped",
            "    env_file: deploy/shared.env",
            "    environment:",
            "      FITNESS_DATA_DIR: /data",
            f"      API_TOKEN: \"{u['token']}\"",
            f"      ELEVEN_MONTHLY_CREDITS: \"{share}\"",
            "    ports:",
            f"      - \"127.0.0.1:{u['port']}:8000\"",
            "    volumes:",
            f"      - data-{name}:/data",
            "    labels:",
            f"      fitness.user: \"{name}\"",
            "",
        ]
    lines.append("volumes:")
    for name in users:
        lines += [f"  data-{name}:", "    labels:", f"      fitness.user: \"{name}\""]
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("name", help="lowercase letters, digits, dashes (becomes the subdomain)")
    ap.add_argument("--domain", default="", help="your domain, e.g. example.com -> https://<name>.example.com")
    ap.add_argument("--rotate-token", action="store_true", help="issue a new token for an existing person")
    ap.add_argument("--eleven-total", type=int, default=9000,
                    help="ElevenLabs credits per month to split across ALL people (default 9000 = free plan 10k minus a margin)")
    a = ap.parse_args()
    name = a.name.strip().lower()
    if not NAME_RE.match(name):
        print("name must be 1-30 chars of a-z, 0-9, '-' (not at the ends)", file=sys.stderr)
        return 2

    USERS.mkdir(exist_ok=True)
    users = load_users()
    new = name not in users
    if new:
        port = max([u["port"] for u in users.values()] + [FIRST_PORT - 1]) + 1
        users[name] = {"port": port, "token": secrets.token_urlsafe(32)}
    elif a.rotate_token:
        users[name]["token"] = secrets.token_urlsafe(32)
    u = users[name]
    (USERS / f"{name}.json").write_text(json.dumps(u, indent=2), encoding="utf-8")

    domain = a.domain.strip().strip("/")
    url = f"https://{name}.{domain}" if domain else f"http://<server-ip>:{u['port']}  (local only; put HTTPS in front for phones)"
    (USERS / f"{name}.txt").write_text(f"Backend URL: {url}\nAPI token:   {u['token']}\n", encoding="utf-8")
    COMPOSE.write_text(render_compose(users, a.eleven_total), encoding="utf-8")

    print(f"{'Added' if new else 'Updated'} {name}: port {u['port']}, {a.eleven_total // len(users)} ElevenLabs credits/month each ({len(users)} people).")
    print(f"URL + token written to {USERS / (name + '.txt')} (keep private; do not commit).")
    print("Next steps:")
    if not (HERE / "shared.env").exists():
        print("  1. cp deploy/shared.env.example deploy/shared.env   and fill in GEMINI_API_KEY / ELEVENLABS_API_KEY")
    print(f"  - docker compose up -d --build        (credits of existing people are re-split, so this restarts them briefly)")
    print(f"  - add `{name}.<yourdomain> {{ reverse_proxy 127.0.0.1:{u['port']} }}` to your Caddyfile and reload Caddy")
    print(f"  - send the person {USERS / (name + '.txt')} over a private channel")
    return 0


if __name__ == "__main__":
    sys.exit(main())
